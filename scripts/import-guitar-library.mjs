// Regenerate the supported guitar subset from the same pinned chords-db revision.
// Usage: node scripts/import-guitar-library.mjs /path/to/downloaded/guitar.json
import { readFileSync, writeFileSync } from "node:fs";
import {
  CHORD_QUALITIES,
  makeChord,
  pitchClassNumber,
} from "../src/lib/music/index.ts";

const revision = "df06fa7b425cf5fd29485ff6591236b3557e3fac";
const database = JSON.parse(readFileSync(process.argv[2], "utf8"));
const roots = ["C", "Db", "D", "Eb", "E", "F", "Gb", "G", "Ab", "A", "Bb", "B"];
const qualities = new Set(CHORD_QUALITIES.map((q) => q.id));
const entries = Object.values(database.chords)
  .flat()
  .filter((c) => qualities.has(c.suffix))
  .map((c) => {
    const chord = makeChord(c.key, c.suffix);
    const allowed = new Set(chord.tones.map((t) => pitchClassNumber(t.note)));
    const positions = c.positions.map(({ frets, fingers, baseFret }) => ({
      frets: frets.map((f) => (f < 0 ? null : f === 0 ? 0 : f + baseFret - 1)),
      // Open and muted strings cannot have a fretting finger.
      fingers: fingers.map((f, i) => (frets[i] > 0 ? Math.max(0, f) : 0)),
      // Derive spans from the supplied fingers: upstream barre flags can be stale.
      barres: [
        ...new Set(
          fingers.flatMap((finger, i) =>
            finger > 0 &&
            frets[i] > 0 &&
            fingers.filter((f, j) => f === finger && frets[j] > 0).length > 1
              ? [frets[i] + baseFret - 1]
              : [],
          ),
        ),
      ],
    }));
    const seen = new Set();
    const valid = positions.filter((position, index) => {
      const ok =
        position.frets.length === 6 &&
        position.fingers.every(
          (finger, i) =>
            finger > 0 === position.frets[i] > 0 &&
            position.fingers.every(
              (other, j) =>
                finger === 0 ||
                other !== finger ||
                (position.frets[j] === position.frets[i] &&
                  position.frets
                    .slice(Math.min(i, j), Math.max(i, j) + 1)
                    .every((f) => f === null || f >= position.frets[i])),
            ),
        ) &&
        !position.frets.some(
          (f, i) =>
            f !== null && !allowed.has(([4, 9, 2, 7, 11, 4][i] + f) % 12),
        );
      if (!ok)
        console.warn(
          `Excluded upstream inconsistent position: ${c.key}:${c.suffix}, position ${index + 1}`,
        );
      const pattern = JSON.stringify(position.frets);
      if (!ok || seen.has(pattern)) return false;
      seen.add(pattern);
      return true;
    });
    if (!valid.length)
      throw new Error(`No valid shapes for ${c.key}:${c.suffix}`);
    return [`${roots[pitchClassNumber(chord.root)]}:${c.suffix}`, valid];
  });
if (entries.length !== 168) throw new Error("Unexpected guitar coverage");
writeFileSync(
  new URL("../src/lib/music/data/guitar-shapes.ts", import.meta.url),
  `// Imported from tombatossals/chords-db at ${revision}.
// MIT © 2016 David Rubert. See public/licenses/chords-db.txt.
// Generated by scripts/import-guitar-library.mjs. Frets/barres are absolute.
import type { LibraryPosition } from "./ukulele-shapes.ts";
export const GUITAR_SHAPES: Record<string, LibraryPosition[]> = ${JSON.stringify(Object.fromEntries(entries))};\n`,
);
console.log(`Imported ${entries.length} guitar chords.`);
