// Prints the pinned, supported subset as TypeScript; does not modify local files.
const revision = "df06fa7b425cf5fd29485ff6591236b3557e3fac";
const url = `https://raw.githubusercontent.com/tombatossals/chords-db/${revision}/lib/ukulele.json`;
const response = await fetch(url);
if (!response.ok) throw new Error(`Upstream returned ${response.status}`);
const database = await response.json();
const qualities = new Set([
  "major",
  "minor",
  "7",
  "maj7",
  "m7",
  "6",
  "m6",
  "sus2",
  "sus4",
  "add9",
  "dim",
  "aug",
  "dim7",
  "m7b5",
]);
const entries = Object.values(database.chords)
  .flat()
  .filter((chord) => qualities.has(chord.suffix))
  .map((chord) => [
    `${chord.key}:${chord.suffix}`,
    chord.positions.map(({ frets, fingers, barres, baseFret }) => ({
      frets: frets.map((fret) =>
        fret < 0 ? null : fret === 0 ? 0 : fret + baseFret - 1,
      ),
      fingers,
      barres: barres.map((fret) => fret + baseFret - 1),
    })),
  ]);
if (
  entries.length !== 168 ||
  entries.flatMap(([, positions]) => positions).length !== 672
)
  throw new Error("Unexpected library coverage");
console.log(`// Imported from tombatossals/chords-db at ${revision}.
// MIT © 2016 David Rubert. See public/licenses/chords-db.txt.
// Generated by scripts/import-ukulele-library.mjs. Frets/barres are absolute.
export type LibraryPosition = {
  frets: (number | null)[];
  fingers: number[];
  barres: number[];
};
export const LIBRARY_REVISION = "${revision}";
export const UKULELE_SHAPES: Record<string, LibraryPosition[]> = ${JSON.stringify(Object.fromEntries(entries), null, 2)};
`);
